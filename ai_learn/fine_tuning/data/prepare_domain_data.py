def create_dataset_from_data(domain_data, repeat_times=50):
    """将数据转换为训练格式并重复"""
    formatted_data = []

    for item in domain_data["data"]:
        text = f"""### Instruction:
{item['instruction']}

### Input:
{item['input']}

### Response:
{item['output']}"""

        formatted_data.append({
            "text": text.strip(),
            "instruction": item['instruction'],
            "output": item['output']
        })

    # 重复数据以增加训练样本
    dataset = Dataset.from_list(formatted_data)
    dataset = dataset.shuffle(seed=42)

    return dataset


def main():
    parser = argparse.ArgumentParser(description='准备特定领域数据集')
    parser.add_argument('--domain', type=str, required=True,
                        choices=['medical', 'legal', 'finance'],
                        help='选择领域: medical(医疗), legal(法律), finance(金融)')
    parser.add_argument('--repeat', type=int, default=50,
                        help='数据重复次数 (默认50)')
    parser.add_argument('--output', type=str, default='./data',
                        help='输出目录 (默认./data)')

    args = parser.parse_args()

    # 选择领域数据
    domain_mapping = {
        'medical': MEDICAL_DATA,
        'legal': LEGAL_DATA,
        'finance': FINANCE_DATA
    }

    selected_data = domain_mapping[args.domain]

    print(f"准备数据集: {selected_data['name']}")
    print(f"描述: {selected_data['description']}")
    print(f"原始数据量: {len(selected_data['data'])} 条")

    # 创建数据集
    dataset = create_dataset_from_data(selected_data, args.repeat)
    total_samples = len(dataset) * args.repeat

    print(f"重复后数据量: {total_samples} 条")

    # 创建输出目录
    output_dir = Path(args.output)
    output_dir.mkdir(exist_ok=True)

    # 保存数据集
    output_file = output_dir / f"{args.domain}_dataset.json"
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(dataset.to_list(), f, ensure_ascii=False, indent=2)

    print(f"✓ 数据已保存到: {output_file}")

    # 显示样例
    print("\n数据样例:")
    print("-" * 50)
    print(dataset[0]['text'][:500] + "...")
    print("-" * 50)

    return dataset


if __name__ == "__main__":
    main()
